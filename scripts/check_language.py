"""Browser coverage for forced EN/PT-BR language and mid-conversation switching."""
import os
from pathlib import Path
from playwright.sync_api import sync_playwright,expect

ROOT=Path(__file__).resolve().parents[1]
BASE=os.environ.get("EMPORIO_TEST_URL","http://127.0.0.1:8770")


def main():
    with sync_playwright() as p:
        browser=p.chromium.launch(headless=True,channel="msedge")
        page=browser.new_page(viewport={"width":1600,"height":1050})
        errors=[];requests=[]
        page.on("pageerror",lambda e:errors.append(str(e)))
        page.on("request",lambda req:requests.append(req.post_data_json) if req.method=="POST" and req.url.endswith("/api/chat") else None)
        page.goto(BASE,wait_until="networkidle")
        en=page.locator('[data-language="en"]');br=page.locator('[data-language="pt-BR"]')
        expect(en).to_have_attribute("aria-pressed","true")
        br.click()
        expect(br).to_have_attribute("aria-pressed","true")
        expect(page.locator("html")).to_have_attribute("lang","pt-BR")
        expect(page.locator("#catalogue-title")).to_have_text("Todos os instrumentos")
        expect(page.locator("#open-settings")).to_have_text("Conectar um modelo ↗")
        page.locator('[data-category="5"]').click()
        expect(page.locator("#catalogue-title")).to_have_text("Violões")
        page.locator('.product-art[data-product="81"]').click()
        expect(page.locator("#ask-product")).to_have_text("Perguntar sobre este instrumento ↗")
        page.locator("#ask-product").click()
        page.locator('#product-questions [data-topic="6"]').click()
        expect(page.locator("#chat-input")).to_have_value("Quais informações de garantia estão disponíveis para este instrumento?")
        page.locator("#send-button").click()
        expect(page.locator("#messages")).to_contain_text("90 dias de garantia legal")
        assert requests[-1]["language"]=="pt-BR"
        expect(br).to_be_enabled()
        en.click()
        expect(en).to_have_attribute("aria-pressed","true")
        expect(page.locator("#catalogue-title")).to_have_text("Acoustic guitars")
        expect(page.locator("#messages")).to_contain_text("90 dias de garantia legal")
        page.locator("#chat-input").fill("Quais são as regras de garantia? Responda em português.")
        page.locator("#send-button").click()
        expect(page.locator(".assistant-message").last).to_contain_text("90 days of legal warranty")
        assert requests[-1]["language"]=="en"
        expect(en).to_be_enabled()
        page.locator("#chat-input").fill("Show electric guitars")
        page.locator("#send-button").click()
        old_card=page.locator(".chat-product").filter(has_text="Fender Stratocaster American Pro II")
        expect(old_card).to_be_visible()
        expect(br).to_be_enabled()
        br.click()
        expect(br).to_have_attribute("aria-pressed","true")
        expect(page.locator("#send-button")).to_be_enabled()
        old_card.click()
        expect(page.locator("#product-detail")).to_contain_text("Guitarra elétrica Fender Stratocaster")
        page.locator("#product-dialog .close-dialog").click()
        en.click()
        expect(en).to_have_attribute("aria-pressed","true")
        expect(page.locator("#send-button")).to_be_enabled()
        page.locator('[data-category="5"]').click()
        page.locator('.product-art[data-product="81"]').click()
        page.locator("#view-product-page").click()
        expect(page.locator(".product-description")).to_contain_text("Classical guitar")
        br.click()
        expect(br).to_have_attribute("aria-pressed","true")
        expect(page.locator(".product-description")).to_contain_text("Violão clássico")
        expect(page.locator("#product-store-policies")).to_contain_text("90 dias de garantia legal")
        expect(page.locator(".price-condition")).to_contain_text("569,91")
        expect(page.locator('.product-section-links a[href="#product-specs"]')).to_have_text("Especificações")
        page.reload(wait_until="networkidle")
        expect(br).to_have_attribute("aria-pressed","true")
        expect(page.locator("html")).to_have_attribute("lang","pt-BR")
        expect(page.locator(".product-description")).to_contain_text("Violão clássico")
        page.screenshot(path=str(ROOT/".runtime/language-desktop.png"))
        page.locator("#open-settings").click()
        expect(page.locator("#settings-dialog h2")).to_have_text("Conecte seu modelo.")
        page.locator("#settings-dialog .close-dialog").click()
        page.set_viewport_size({"width":390,"height":844})
        expect(en).to_be_visible();expect(br).to_be_visible()
        assert page.evaluate("document.documentElement.scrollWidth<=innerWidth")
        page.screenshot(path=str(ROOT/".runtime/language-mobile.png"))
        en.click()
        expect(en).to_have_attribute("aria-pressed","true")
        expect(page.locator(".product-description")).to_contain_text("Classical guitar")
        assert not errors,errors
        browser.close()
    print("Language browser checks passed: pressed switch, translated chrome/products/policies, mid-chat enforcement, preserved history, reload persistence, settings and mobile layout.")


if __name__=="__main__":main()
